/* ---------------- Employees ----------------
   Terse builder so the roster stays readable and every record is
   guaranteed to have the same shape.                                    */
interface EmpSpec {
  id: string;
  name: string;
  dept: string;
  designation: string;
  manager: string | null;
  joining: string;
  salary: number;
  grade: string;
  email?: string;
  phone?: string;
  gender?: Employee['gender'];
  dob?: string;
  location?: string;
  employmentType?: Employee['employmentType'];
  status?: Employee['status'];
  experience?: string;
  bloodGroup?: string;
}

function makeEmployee(spec: EmpSpec): Employee {
  const slug = spec.name.toLowerCase().replace(/[^a-z ]/g, '');
  const local = spec.email
    ? spec.email.split('@')[0]
    : slug.split(/\s+/).slice(0, 2).join('.');
  const phoneSeed = 20000 + Math.round(hash01(spec.id) * 79999);
  return {
    id: spec.id,
    name: spec.name,
    email: spec.email || `${local}@cyethack.com`,
    phone: spec.phone || `+91 98110 ${phoneSeed}`,
    gender: spec.gender || 'Male',
    dob: spec.dob || `199${Math.round(hash01(spec.id + 'dob') * 8) + 1}-0${Math.round(hash01(spec.id + 'm') * 8) + 1}-1${Math.round(hash01(spec.id + 'd') * 8)}`,
    dept: spec.dept,
    designation: spec.designation,
    manager: spec.manager,
    location: spec.location || 'Noida',
    employmentType: spec.employmentType || 'Full-time',
    joining: spec.joining,
    status: spec.status || 'Active',
    probation: spec.status === 'Probation',
    experience: spec.experience || '3 yrs',
    salary: spec.salary,
    grade: spec.grade,
    bloodGroup: spec.bloodGroup || 'B+',
  };
}

